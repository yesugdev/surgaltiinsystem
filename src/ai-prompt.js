/**
 * Багш ChatGPT, Claude, Gemini гэх мэт AI-д хуулж өгөх prompt.
 * AI-ийн гаралтыг асуулт олноор оруулах хуудсанд шууд буулгахад бэлэн форматтай байна.
 */
function buildImportPrompt({ subjectName, examTitle } = {}) {
  return `Чи туршлагатай ${subjectName ? subjectName + ' хичээлийн ' : ''}багш. Доорх ДААЛГАВРЫН дагуу шалгалтын асуултуудыг ЯГ дараах форматаар гарга.
Форматаас гадна ямар ч оршил, тайлбар, гарчиг, markdown тэмдэглэгээ (**, #, \`\`\`, жагсаалтын - эсвэл *) бүү бич. Зөвхөн асуултууд.

ФОРМАТ:
1. Асуултын текст
A) Сонголт
*B) Зөв сонголт
C) Сонголт
D) Сонголт

2. Олон зөв хариулттай асуулт
*A) Зөв сонголт
B) Сонголт
*C) Зөв сонголт
D) Сонголт
Оноо: 2

3. Богино нээлттэй асуулт
Хариулт: Зөв хариулт | Өөр зөв хувилбар

4. Эссэ, тайлбар шаардсан асуулт
Хариулт:
Оноо: 5

ДҮРЭМ:
- Асуулт бүр дугаар, цэгээр эхэлнэ (1. 2. 3. ...). Асуултуудын хооронд нэг хоосон мөр авна.
- Сонголт бүр шинэ мөрөнд A) B) C) D) хэлбэрээр бичигдэнэ.
- Зөв сонголтын ӨМНӨ * тэмдэг тавина (жишээ: *B) ...). Бусад сонголтод * тавихгүй.
- Нэг зөв хариулттай асуултад яг нэг *, олон зөв хариулттай асуултад бүх зөв сонголтод * тавина.
- Сонголтгүй богино хариулттай асуултад "Хариулт:" мөрөнд зөв хариултыг бичнэ. Хэд хэдэн зөв хувилбар байвал | тэмдгээр тусгаарлана.
- Эссэ, тайлбар шаардсан асуултад "Хариулт:" мөрийг хоосон үлдээнэ (багш гараар дүгнэнэ).
- "Оноо: N" мөр заавал биш. Бичээгүй бол 1 оноо.
- Томьёо, тэмдэгтийг энгийн текстээр бичнэ (жишээ: x^2, √2, 3/4, H2O).
- Буруу сонголтууд үнэмшилтэй байх ба зөв хариултын байрлалыг (A, B, C, D) санамсаргүй тараана.
- Асуултыг монгол хэлээр, тухайн ангийн түвшинд тохирсон, ойлгомжтой бичнэ.

ДААЛГАВАР:
${subjectName ? `Хичээл: ${subjectName}\n` : ''}${examTitle ? `Шалгалт: ${examTitle}\n` : ''}Анги: [жишээ: 9-р анги]
Сэдэв: [жишээ: Квадрат тэгшитгэл]
Асуултын тоо: [жишээ: 15 сонгох, 3 нээлттэй]
Хүндийн түвшин: [хөнгөн / дунд / хүнд]
[Эсвэл өөрийн бэлэн тест, хичээлийн материалыг энд буулгаад "Үүнийг дээрх формат руу хөрвүүл" гэж бичнэ үү.]
`;
}

/**
 * Хичээлийн онол + даалгавруудыг нэг дор бэлтгүүлэх prompt. Хоёр формат — ХОЛИХГҮЙ:
 *  - markdown: цэвэр Markdown, томьёо энгийн текст/Unicode-оор (x², √2) — $ ба LaTeX хэрэглэхгүй
 *  - latex: бүтэн LaTeX баримт (\section*{=== ОНОЛ ===} …) — Markdown хэрэглэхгүй
 * Гаралтыг «Хичээл → Онол, даалгавар оруулах» хуудсанд тухайн форматыг сонгоод буулгана.
 */
function lessonTask({ subjectName, lessonTitle, classNames }) {
  return `ДААЛГАВАР:
${subjectName ? `Хичээлийн төрөл: ${subjectName}\n` : ''}${lessonTitle ? `Хичээлийн сэдэв: ${lessonTitle}\n` : 'Хичээлийн сэдэв: [жишээ: Квадрат тэгшитгэл]\n'}Анги: ${classNames || '[жишээ: 9-р анги]'}
Онолын хэмжээ: [жишээ: 1 цагийн хичээлд тохирох, дунд зэрэг]
Тест: [жишээ: 1 тест, 10 асуулт (8 сонгох, 2 нээлттэй)]
Даалгавар: [жишээ: 1 бие даалт — 5 бодлого бодож зургаар илгээх]
[Эсвэл өөрийн бэлтгэсэн материал, сурах бичгийн хэсгийг энд буулгаад "Үүн дээр тулгуурлаж дээрх бүтцээр гарга" гэж бичнэ үү.]
`;
}

const COMMON_RULES = `- ОНОЛ хэсэг нэг л байна. ТЕСТ, ДААЛГАВАР хэсэг хэд ч байж болно.
- Онол нь ойлгомжтой, дэс дараатай, жишээтэй, тухайн ангийн түвшинд тохирсон байна.
- ТЕСТ: асуулт бүр дугаартай. Сонголт бүр ШИНЭ МӨРӨНД A) B) C) D). Зөв сонголтын ӨМНӨ * тавина (*B) …). Олон зөв хариулттай бол бүх зөв сонголтод *. Сонголтгүй асуултад "Хариулт:" мөрөнд зөв хариултыг бичиж, хувилбаруудыг | тэмдгээр тусгаарлана. Эссэ асуултад "Хариулт:" мөрийг хоосон үлдээнэ. Зөв хариултын байрлалыг санамсаргүй тараана.
- Тестийн асуултууд зөвхөн ОНОЛ хэсэгт орсон агуулгад тулгуурлана.
- "Оноо: N" мөр заавал биш (тест асуултад анхдагч 1, даалгаварт 10). Даалгаврын "Оноо:" мөр нь хэсгийн эхний мөр байна.
- ДААЛГАВАР нь онол дээр суурилсан бүтээлч/практик ажил байна. Юуг, ямар хэлбэрээр (Word, PDF, зураг, код) илгээх, хэрхэн үнэлэхийг тодорхой бичнэ.
- Бүх агуулгыг монгол хэлээр бичнэ.`;

function buildMarkdownLessonPrompt(opts = {}) {
  const { subjectName } = opts;
  return `Чи туршлагатай ${subjectName ? subjectName + ' хичээлийн ' : ''}багш, сурах бичгийн зохиогч. Доорх ДААЛГАВРЫН дагуу нэг хичээлийн ОНОЛ болон ДААЛГАВРУУДЫГ ЗӨВХӨН MARKDOWN форматаар, ЯГ дараах бүтцээр гарга.
Бүтцээс гадна ямар ч оршил, дүгнэлт, тайлбар бүү бич. LaTeX (\\frac, \\sqrt, $…$, \\documentclass г.м.) ОГТ хэрэглэхгүй. HTML tag бичихгүй. Бүх гаралтыг \`\`\` блок дотор хийхгүй.

БҮТЭЦ (хэсэг бүр "===" тэмдэглэгээтэй мөрөөр эхэлнэ):

=== ОНОЛ ===
## Үндсэн гарчиг
Онолын агуулга. Томьёо энгийн текстээр: a² + b² = c².

### Дэд гарчиг
- Жагсаалтын зүйл, **тод**, *налуу*, \`Alt + =\` гэх мэт товчлуур/команд
1. Дугаартай алхам

| Багана | Багана |
|---|---|
| утга | √2 |

> 💡 Анхаарах зүйл, санамж

=== ТЕСТ: Тестийн нэр ===
(Заавал биш: тестийн товч заавар нэг мөрөөр)
1. Асуултын текст
A) Сонголт
*B) Зөв сонголт
C) Сонголт
D) Сонголт

2. Олон зөв хариулттай асуулт
*A) Зөв сонголт
B) Сонголт
*C) Зөв сонголт
Оноо: 2

3. Богино нээлттэй асуулт
Хариулт: Зөв хариулт | Өөр зөв хувилбар

=== ДААЛГАВАР: Даалгаврын нэр ===
Оноо: 10
Даалгаврын дэлгэрэнгүй заавар Markdown форматаар: юу хийх, ямар хэлбэрээр илгээх, үнэлэх шалгуур.

ДҮРЭМ — БҮТЭЦ:
- "=== ОНОЛ ===", "=== ТЕСТ: нэр ===", "=== ДААЛГАВАР: нэр ===" мөрүүдийг яг ингэж бич (гурван тэнцүү тэмдэг, том үсэг). Эдгээр мөрийг тод болгох, гарчиг болгох хэрэггүй.
${COMMON_RULES}

ДҮРЭМ — MARKDOWN:
- Гарчиг: "## " (үндсэн), "### " (дэд). "# " ашиглахгүй.
- Жагсаалт: "- " эсвэл "1. ". Дэд жагсаалтыг 2 зайгаар доголно. Мөрийн эхэнд 4 зай авахгүй (код болж харагдана).
- Хүснэгт: эхний мөр толгой, дараагийн мөр |---|---|.
- Код (програмчлалын хичээлд): \`\`\`cpp, \`\`\`python гэх мэт хэлийг заасан блок. Мөр доторх код, товчлуурын нэр: \`…\`.
- Тестийн асуулт, сонголтод **, #, - зэрэг тэмдэглэгээ бүү хэрэглэ.

ДҮРЭМ — ТОМЬЁО (LaTeX-гүй):
- Томьёог энгийн текст ба Unicode тэмдэгтээр: x², x³, x₁, √2, ∛8, ½, ¾, π, α, β, θ, ≤, ≥, ≠, ±, ×, ÷, ∞, H₂O, CO₂, E = mc², (a + b)/c.
- $ тэмдэг, \\frac, \\sqrt зэрэг LaTeX команд ОГТ бичихгүй.

ХУУЛАХ: Хариултаа AI-ийн «Copy / Хуулах» товчоор хуулна уу (харагдаж буй текстийг хулганаар сонгож хуулбал Markdown алдагдана).

${lessonTask(opts)}`;
}

