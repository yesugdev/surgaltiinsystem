/** format: 'markdown' (анхдагч) | 'latex' */
function buildLessonPrompt(opts = {}) {
  return opts.format === 'latex' ? buildLatexLessonPrompt(opts) : buildMarkdownLessonPrompt(opts);
}

module.exports = { buildImportPrompt, buildLessonPrompt, buildMarkdownLessonPrompt, buildLatexLessonPrompt };
